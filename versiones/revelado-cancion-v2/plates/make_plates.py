def polygon(size, points):
    m=Image.new('L',size,0)
    ImageDraw.Draw(m).polygon([(round(x*size[0]),round(y*size[1])) for x,y in points],fill=255)
    return m

def prepare(name):
    spec=SPECS[name]; size=(spec['w'],H)
    source=ROOT/(name+'_source.png')
    if not source.exists():
        raise SystemExit(f'Missing original matrix: {source}. See README; this script does not regenerate AI art.')
    with Image.open(source) as im:
        im.convert('RGB').resize(size,Image.Resampling.LANCZOS).save(ROOT/(name+'.jpg'),quality=96,subsampling=0)
    channels=[]
    for key in ['water','rock','sky']:
        canvas=Image.new('L',size,0)
        for pts in ([spec[key]] if key=='sky' else spec[key]):
            m=polygon(size,pts);canvas.paste(255,(0,0),m)
        channels.append(canvas.filter(ImageFilter.GaussianBlur(1.4)))
    channels[2]=ImageChops.subtract(channels[2], ImageChops.lighter(channels[0],channels[1]))
    Image.merge('RGB',channels).save(ROOT/(name+'_mask.png'))
    print(name, size, flush=True)

if __name__=='__main__':
    for name in sys.argv[1:] or SPECS:
        prepare(name)
